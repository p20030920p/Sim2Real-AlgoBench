"""Registry helpers that turn algo_registry.yaml into runnable Nav2 config.

Two things happen here:

1. Every entry in the registry becomes a *named Nav2 planner plugin instance*.
   They are all registered at once, so Nav2 holds all algorithms loaded and can
   switch between them per goal via the ComputePathToPose ``planner_id`` field.
2. A behaviour tree is generated per entry, with ``planner_id`` baked in. Since
   ``NavigateToPose`` carries a ``behavior_tree`` field but no planner id, this
   is what lets the mission node pick an algorithm per goal without restarting
   anything.

Nothing here is Nav2-specific magic; it is ordinary parameter and XML plumbing
that would otherwise be copy-pasted once per algorithm.
"""

from __future__ import annotations

import os
from typing import Any, Dict, List, Optional

import yaml

# Parameters forwarded from the registry to algo_core through the plugin.
FORWARDED_PARAMS = (
    "cost_scale",
    "snap_radius",
    "weight",
    "allow_diagonal",
    "remove_collinear",
    "smooth",
)

BEHAVIOR_TREE_TEMPLATE = """\
<!-- Generated by algo_bringup from algo_registry.yaml. Do not edit by hand. -->
<!-- algorithm: {algorithm} -->
<root main_tree_to_execute="MainTree">
  <BehaviorTree ID="MainTree">
    <PipelineSequence name="NavigateWithReplanning">
      <RateController hz="{replan_hz}">
        <RecoveryNode number_of_retries="1" name="ComputePathToPose">
          <ComputePathToPose goal="{{goal}}" path="{{path}}" planner_id="{planner_id}"/>
          <ClearEntireCostmap name="ClearGlobalCostmap-Context"
                              service_name="global_costmap/clear_entirely_global_costmap"/>
        </RecoveryNode>
      </RateController>
      <RecoveryNode number_of_retries="1" name="FollowPath">
        <FollowPath path="{{path}}" controller_id="{controller_id}"/>
        <ClearEntireCostmap name="ClearLocalCostmap-Context"
                            service_name="local_costmap/clear_entirely_local_costmap"/>
      </RecoveryNode>
    </PipelineSequence>
  </BehaviorTree>
</root>
"""


def load_registry(path: str) -> Dict[str, Any]:
    """Read the registry YAML."""
    with open(path, "r", encoding="utf-8") as handle:
        return yaml.safe_load(handle)


def planners(registry: Dict[str, Any]) -> List[Dict[str, Any]]:
    return list(registry.get("planners", []))


def controllers(registry: Dict[str, Any]) -> List[Dict[str, Any]]:
    return list(registry.get("controllers", []))


def by_index(registry: Dict[str, Any], table: str, index: int) -> Optional[Dict[str, Any]]:
    for entry in registry.get(table, []):
        if int(entry["index"]) == int(index):
            return entry
    return None


def active_planner(registry: Dict[str, Any]) -> Dict[str, Any]:
    """The planner selected by ``active.planner`` — the one number to change."""
    index = int(registry.get("active", {}).get("planner", 0))
    entry = by_index(registry, "planners", index)
    if entry is None:
        raise KeyError(
            f"active.planner = {index} does not match any entry in `planners`"
        )
    return entry


def active_controller(registry: Dict[str, Any]) -> Dict[str, Any]:
    index = int(registry.get("active", {}).get("controller", 0))
    entry = by_index(registry, "controllers", index)
    if entry is None:
        raise KeyError(
            f"active.controller = {index} does not match any entry in `controllers`"
        )
    return entry


def planner_server_params(
    registry: Dict[str, Any],
    plugin_class: str = "algo_nav2_plugins/GridPlanner",
    publish_expanded: bool = False,
) -> Dict[str, Any]:
    """Build the ``planner_server`` parameter block for every registered entry.

    Entries marked ``external: true`` are Nav2's own plugins and are referenced
    by their real class name; everything else is served by the single
    ``algo_nav2_plugins/GridPlanner`` adapter, parameterised by ``algorithm``.
    """
    ids: List[str] = []
    params: Dict[str, Any] = {}

    for entry in planners(registry):
        planner_id = entry["id"]
        ids.append(planner_id)

        if entry.get("external"):
            block: Dict[str, Any] = {"plugin": entry["algorithm"]}
        else:
            block = {
                "plugin": plugin_class,
                "algorithm": entry["algorithm"],
                "publish_expanded": publish_expanded,
            }

        for key in FORWARDED_PARAMS:
            if key in entry.get("params", {}):
                block[key] = entry["params"][key]

        params[planner_id] = block

    return {"planner_plugins": ids, **params}


def write_behavior_trees(
    registry: Dict[str, Any],
    out_dir: str,
    controller_id: str = "FollowPath",
    replan_hz: float = 1.0,
) -> Dict[int, str]:
    """Write one behaviour tree per planner and return ``index -> path``.

    The mission node selects an algorithm by handing the matching file name to
    ``NavigateToPose.behavior_tree``.
    """
    os.makedirs(out_dir, exist_ok=True)
    mapping: Dict[int, str] = {}

    for entry in planners(registry):
        planner_id = entry["id"]
        content = BEHAVIOR_TREE_TEMPLATE.format(
            algorithm=entry["algorithm"],
            planner_id=planner_id,
            controller_id=controller_id,
            replan_hz=replan_hz,
        )
        path = os.path.join(out_dir, f"navigate_{planner_id}.xml")
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(content)
        mapping[int(entry["index"])] = path

    return mapping


def selection_for_state(registry: Dict[str, Any], state: str) -> Optional[str]:
    """Planner id configured for a mission state, if any."""
    return registry.get("selection", {}).get("by_state", {}).get(state)


def describe(registry: Dict[str, Any]) -> str:
    """Human-readable table, printed at launch so the active algorithm is never
    a mystery."""
    lines = ["", "=" * 78, "  ALGORITHM INDEX", "=" * 78]
    active = active_planner(registry)["index"]
    for entry in planners(registry):
        marker = "->" if int(entry["index"]) == int(active) else "  "
        lines.append(
            f" {marker} [{entry['index']:>2}] {entry['id']:<22} {entry['algorithm']}"
        )
        lines.append(f"        {entry.get('description', '')}")
    lines.append("=" * 78)
    lines.append(
        f"  active planner: [{active}] {active_planner(registry)['id']}"
        "   (change active.planner in algo_registry.yaml)"
    )
    lines.append("=" * 78)
    lines.append("")
    return "\n".join(lines)
